"""Question model plus local storage for custom questions and attempt history.

Storage layout (inside the data directory, ``user_data/`` by default):

    questions/<question-id>.json   one file per user-created question
    history.jsonl                  one JSON object per checked attempt
    history_backups/               copies made automatically before each reset
"""

from __future__ import annotations

import json
import os
import re
import shutil
import tempfile
import uuid
from dataclasses import asdict, dataclass
from datetime import datetime
from pathlib import Path

PACKAGE_DIR = Path(__file__).resolve().parent
PROJECT_DIR = PACKAGE_DIR.parent
BUILTIN_QUESTIONS_FILE = PACKAGE_DIR / "data" / "builtin_questions.json"
DEFAULT_DATA_DIR = PROJECT_DIR / "user_data"
DATA_DIR_ENV = "SQL_HELPER_DATA_DIR"

DIFFICULTIES = ("Easy", "Medium", "Hard")
SOURCE_BUILTIN = "builtin"
SOURCE_CUSTOM = "custom"


@dataclass
class Question:
    id: str
    title: str
    prompt: str
    solution: str
    difficulty: str = "Easy"
    topic: str = "General"
    hint: str = ""
    order_matters: bool = False
    generated: bool = False          # made by the question generator (added in v1.1)
    source: str = SOURCE_CUSTOM

    @property
    def is_custom(self) -> bool:
        return self.source == SOURCE_CUSTOM

    @classmethod
    def from_dict(cls, data: dict, source: str) -> "Question":
        """Build a Question, ignoring unknown keys so older/newer files still load."""
        missing = [k for k in ("id", "title", "prompt", "solution") if not data.get(k)]
        if missing:
            raise ValueError(f"missing required field(s): {', '.join(missing)}")
        known = {k: data[k] for k in cls.__dataclass_fields__ if k in data and k != "source"}
        return cls(**known, source=source)

    def to_dict(self) -> dict:
        data = asdict(self)
        data.pop("source")  # derived from where the file lives, not stored
        return data


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug[:40] or "question"


def _atomic_write(path: Path, text: str) -> None:
    """Write via a temp file + rename so a crash never leaves a half-written file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


class QuestionStore:
    """Loads built-in questions and reads/writes the user's local data folder."""

    def __init__(self, data_dir: Path | None = None) -> None:
        env_dir = os.environ.get(DATA_DIR_ENV)
        self.data_dir = Path(data_dir or env_dir or DEFAULT_DATA_DIR)
        self.questions_dir = self.data_dir / "questions"
        self.history_file = self.data_dir / "history.jsonl"
        self.backup_dir = self.data_dir / "history_backups"
        self.warnings: list[str] = []  # problems found while loading, shown in the UI

    # ---- questions -----------------------------------------------------
    def load_builtin(self) -> list[Question]:
        with open(BUILTIN_QUESTIONS_FILE, encoding="utf-8") as fh:
            return [Question.from_dict(d, SOURCE_BUILTIN) for d in json.load(fh)]

    def load_custom(self) -> list[Question]:
        questions = []
        if not self.questions_dir.is_dir():
            return questions
        for path in sorted(self.questions_dir.glob("*.json")):
            try:
                with open(path, encoding="utf-8") as fh:
                    questions.append(Question.from_dict(json.load(fh), SOURCE_CUSTOM))
            except (OSError, ValueError, TypeError, AttributeError) as exc:
                self.warnings.append(f"Skipped {path.name}: {exc}")
        return questions

    def load_all(self) -> list[Question]:
        self.warnings = []
        return self.load_builtin() + self.load_custom()

    def new_id(self, title: str) -> str:
        return f"custom-{slugify(title)}-{uuid.uuid4().hex[:6]}"

    def _path_for(self, question: Question) -> Path:
        # The id is generated by new_id(), but sanitize anyway so a hand-edited
        # file can never point outside the questions folder.
        return self.questions_dir / f"{slugify(question.id)}.json"

    def save_custom(self, question: Question) -> Path:
        if not question.is_custom:
            raise ValueError("Built-in questions are read-only.")
        path = self._path_for(question)
        _atomic_write(path, json.dumps(question.to_dict(), indent=2) + "\n")
        return path

    def delete_custom(self, question: Question) -> None:
        if not question.is_custom:
            raise ValueError("Built-in questions can't be deleted.")
        self._path_for(question).unlink(missing_ok=True)

    # ---- history -------------------------------------------------------
    def record_attempt(self, question_id: str, sql: str, correct: bool) -> None:
        self.data_dir.mkdir(parents=True, exist_ok=True)
        entry = {
            "timestamp": datetime.now().isoformat(timespec="seconds"),
            "question_id": question_id,
            "sql": sql,
            "correct": correct,
        }
        with open(self.history_file, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry) + "\n")

    def load_history(self) -> list[dict]:
        entries = []
        if not self.history_file.exists():
            return entries
        with open(self.history_file, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    entries.append(json.loads(line))
                except json.JSONDecodeError:
                    continue  # tolerate a damaged line rather than losing all history
        return entries

    def reset_history(self, question_id: str | None = None) -> Path | None:
        """Clear saved attempts for one question, or for all questions when None.

        The current history file is copied to ``history_backups/`` first, so a
        reset can always be undone by hand. Returns the backup path, or None if
        there was no history to reset.
        """
        if not self.history_file.exists():
            return None
        self.backup_dir.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S-%f")
        backup = self.backup_dir / f"history-{stamp}.jsonl"
        shutil.copy2(self.history_file, backup)

        if question_id is None:
            self.history_file.unlink()
            return backup

        kept = []
        with open(self.history_file, encoding="utf-8") as fh:
            for line in fh:
                try:
                    if json.loads(line).get("question_id") == question_id:
                        continue
                except (json.JSONDecodeError, AttributeError):
                    pass  # keep lines we can't read rather than silently dropping them
                kept.append(line if line.endswith("\n") else line + "\n")
        _atomic_write(self.history_file, "".join(kept))
        return backup

    def solved_ids(self) -> set[str]:
        return {e.get("question_id") for e in self.load_history() if e.get("correct")}
